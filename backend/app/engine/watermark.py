"""Marquage des résultats : filigrane visible et métadonnée « généré par IA »."""
from __future__ import annotations

from pathlib import Path

import cv2
import numpy as np
from PIL import Image, PngImagePlugin

AI_NOTICE = "AI-generated by Jideo"
EXIF_IMAGE_DESCRIPTION = 0x010E


def add_visible_watermark(img: np.ndarray, text: str = "Jideo") -> np.ndarray:
    out = img.copy()
    h, w = out.shape[:2]
    scale = max(0.4, min(w, h) / 1200)
    thickness = max(1, round(scale * 2))
    font = cv2.FONT_HERSHEY_SIMPLEX
    (tw, _), _ = cv2.getTextSize(text, font, scale, thickness)
    margin = max(6, round(14 * scale))
    origin = (w - tw - margin, h - margin)
    overlay = out.copy()
    cv2.putText(overlay, text, origin, font, scale, (0, 0, 0), thickness + 2, cv2.LINE_AA)
    cv2.putText(overlay, text, origin, font, scale, (255, 255, 255), thickness, cv2.LINE_AA)
    return cv2.addWeighted(overlay, 0.6, out, 0.4, 0)


def save_image(img: np.ndarray, path: Path) -> None:
    pil = Image.fromarray(np.ascontiguousarray(img[:, :, ::-1]))
    if path.suffix.lower() == ".png":
        info = PngImagePlugin.PngInfo()
        info.add_text("Description", AI_NOTICE)
        pil.save(path, pnginfo=info)
        return
    exif = Image.Exif()
    exif[EXIF_IMAGE_DESCRIPTION] = AI_NOTICE
    pil.save(path, exif=exif.tobytes(), quality=95)
